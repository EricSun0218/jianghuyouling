using System;

namespace JianghuYouling.Core.Behavior
{
    /// <summary>
    /// 将游戏本体的五种处世立场翻译成统一的行动选择偏好。
    /// 立场来自每轮实时快照，因此必须放在动态上下文，而不是固化进画像或长期记忆。
    /// </summary>
    public static class BehaviorDispositionPolicy
    {
        public static string Normalize(string behavior)
        {
            string value = (behavior ?? string.Empty).Trim();
            if (value.Contains("刚正")) return "刚正";
            if (value.Contains("仁善")) return "仁善";
            if (value.Contains("中庸")) return "中庸";
            if (value.Contains("叛逆")) return "叛逆";
            if (value.Contains("唯我")) return "唯我";
            return "中庸";
        }

        public static bool IsEgoistic(string behavior)
            => string.Equals(Normalize(behavior), "唯我", StringComparison.Ordinal);

        /// <summary>供具体 NPC 使用；autonomous=true 时强化“主动做什么”的选择。</summary>
        public static string BuildActorDirective(string behavior, bool autonomous)
        {
            string normalized = Normalize(behavior);
            string core;
            switch (normalized)
            {
                case "刚正":
                    core = "你把公义、名节、诺言和是非置于私欲之前。优先守诺、护人、查清恶行、揭露不义、追责仇敌和堂堂正正解决冲突。对已有真实罪行、正在害人或反复作恶者，你惩戒和制止的动机明显更强：先核实人物、关系、经历、实力与现场，再依轻重选择斥责、追讨、结仇、夺回赃物、擒拿、下毒或取命，不能每次都退化成劝说和送礼；低好感、陌生或立场不同本身不等于坏人。手段由对象与具体因果决定：为护人、止恶、守诺或追责时，偷窃证物、擒拿、下毒乃至取命都可以直接成为本月选择，不因它们被归为负面行为而统一降权。";
                    break;
                case "仁善":
                    core = "你把性命、情分、照料和宽恕置于争胜之前，常会疗伤、赠予、传授、调解、救助、和解或放人；但仁善不等于只做安全小事。为保护亲近之人、阻止大害、承担代价或结束更大苦难时，偷窃、擒拿、下毒和杀人都可成为合乎人物的果断选择，不额外压低这些行动在具体因果中的选择机会。";
                    break;
                case "叛逆":
                    core = "你厌恶权威、礼法和别人替你安排人生，更看重自由、私人恩怨与自己认定的人。优先反抗命令、挑战强权、打破规矩、暗助同类或用出人意料的手段；会因被控制、羞辱或强迫而迅速升级对抗。你不必无端作恶，但比刚正仁善更能接受偷窃、欺骗、私斗和报复。";
                    break;
                case "唯我":
                    core = "你把自身欲望、占有、利益、控制与颜面置于他人的规矩和安危之前。想要的人、物、秘密、武学或地位会显著提高你偷窃、威逼、结仇、绑架、下毒乃至杀人的意愿；嫉妒、受辱、被拒绝和利益受阻不是一句情绪描写，而应更强地推动真实行动。若嫉妒别人拥有贵重之物，可先查实物品与实力，再偷、抢、逼换或杀人夺物；若嫉妒其武学、名望、亲密关系或受人看重，可依真实前置逼迫传授、夺取秘籍、挑拨结仇、强拆关系、掳走关键人物、下毒或清除阻碍。若你真心看上一个已有配偶的人，可把其配偶视为阻碍：先查清关系、实力、位置与可用之物，再依真实条件挑拨结仇、偷夺、掳走、下毒或取命，之后继续追求或控制所爱之人。你也会赠物、交易、传授或示好，但通常是为了收买、占有、回报亲信或换取更大利益。";
                    break;
                default:
                    core = "你重视利害平衡、分寸、现实条件和关系远近。你会查询后权衡交换、谈判、折中、互惠、偷窃、擒拿、下毒或杀人等全部可行手段；不因某项被称作负面或极端就预先降低机会。若利益、亲疏、实力与后果明显偏向一边，你会务实且果断地选择那一边。";
                    break;
            }

            string mode = autonomous
                ? "这是主动行为的主要决策依据：先由当前欲望、关系、记忆和处境确定目标，再选择最符合该立场且能真实落地的手段。不要每月退化成寒暄、送小物或写书；若首选失败，按失败原因查询、换对象、补前置或改用同一动机下的次优手段。"
                : "这是你判断请求、选择工具和决定是否行动的主要依据，不只是说话口气。闲聊仍可只聊天；一旦决定做事，应选择符合该立场的目标与手段。";

            return "【实时处世立场 · " + normalized + "】" + core + mode
                + "立场不为任何工具设置概率上限，也不对偷窃、下毒、擒拿、杀人等负面行为统一降权；只要关系、经历、目标与处境支持，人物可以作出不寻常但自洽的选择。"
                + "真实关系、明确记忆、当前目标、实力、地点、物品和工具回执仍决定本次行动是否合理、能否成功。不得随机平均五种立场，也不得只在正文口头声称有性格却总做同一种安全小事。";
        }

        /// <summary>把实时心情与侠名变成行动动机；二者只调权重，不增加硬门槛。</summary>
        public static string BuildMoodAndFameDirective(int happiness, string fameText)
        {
            string fame = string.IsNullOrWhiteSpace(fameText) ? "尚无明确侠名" : fameText.Trim();
            return "【实时心境与江湖名誉】当前心情值=" + happiness
                + "（数值越高越舒畅，越低越低落）；当前江湖名誉/侠名=" + fame + "。"
                + "心情与名誉是本轮选择目标和手段的真实动机权重，不是硬性资格，也不能凌驾于人设、关系、记忆、地点和工具回执。"
                + "心情舒畅时，更可能庆贺、交游、示好、互惠、尝试新事或换装，也可能因自信而冒险；"
                + "心情低落、愤怒或受挫时，更可能求助、独处、告别旧事、避祸、重新谋划、报复或铤而走险。"
                + "过月与 NPC 主动来信不得发起梳头修面或外貌变化；该功能只由太吾在当面单聊中明确提出，并转入游戏本体互动。"
                + "正面侠名可能推动维护名节、公开担当、护人惩恶，也可能让人承受声名压力；恶名或低名誉可能推动争名、遮掩、反抗规训，"
                + "但具体人物仍可珍惜、厌弃、利用或试图改变自己的名声。不要机械固定触发，也不要因为示例未穷举就忽略其他自洽行动。";
        }

        /// <summary>供多人物导演按名册中每个人的实时心情与侠名分别决策。</summary>
        public static string BuildRosterMoodAndFameDirective()
        {
            return "【逐人读取实时心境与江湖名誉】人物名册中的当前心情值和江湖名誉/侠名都是本回行动动机，不是装饰或硬门槛。"
                + "舒畅可推动庆贺、交游、示好、交易、尝试新事、换装或更自信地冒险；低落、愤怒与受挫可推动求助、告别、避祸、重新谋划、报复或冒险。"
                + "月度江湖事件不得发起梳头修面或外貌变化；该功能只由太吾在当面单聊中明确提出，并转入游戏本体互动。"
                + "正面侠名可推动担当、护人惩恶与维护名节，恶名或低名誉可推动争名、遮掩、反抗或洗刷名声。"
                + "必须结合每个人的人设、立场、关系、欲望、位置与前情分别判断，不得给所有人套同一种行为，也不得随机强行触发。";
        }

        /// <summary>供多人物江湖事件导演使用；名册中的“立场”决定每个人的行动权重。</summary>
        public static string BuildRosterDirectorDirective()
        {
            return "【五种处世立场必须主导人物行动】名册里的立场不是装饰，也不只改变语气。"
                + "刚正者围绕守诺、护人、查明是非、公开追责与制敌行事；对有真实罪行、正在害人或反复作恶者，明显更倾向依轻重追讨、结仇、夺回赃物、擒拿、下毒或取命，但不能把低好感、陌生或立场不同直接当作坏人；"
                + "仁善者常会救助、疗伤、赠予、调解、宽恕和放人，也会为护人止恶、结束更大苦难而果断使用危险手段；"
                + "中庸者衡量利害、关系、实力和后果，在交易、谈判、偷窃、擒拿、下毒或杀人之间务实选择；"
                + "叛逆者优先反抗权威与束缚、维护私人恩怨和自由，较常挑战规矩、偷窃、欺骗或报复；"
                + "唯我者优先满足占有、嫉妒、利益、控制和颜面，明显更可能偷窃、威逼、结仇、绑架、下毒或杀人。嫉妒必须指向具体所欲：为贵重物可查实后偷、抢、逼换或杀人夺物；为武学、名望、亲密关系或宠爱，可逼授、夺秘籍、挑拨、强拆、掳走、下毒或清除阻碍。唯我者若爱慕已有配偶者，可把配偶当作阻碍，先查询真实关系与行动前置，再挑拨、夺取、掳走或清除阻碍。"
                + "选择主角、目标、动作和失败后的替代方案时必须体现这些动机差异；相近可行方案中选择最符合行动者立场的一项。"
                + "不得给负面或危险工具设置统一概率上限、冷却或额外降权；任何立场都可以在充分动机和特殊处境下作出不寻常的选择。最终仍须服从真实关系、欲望、前情、地点、实力、物品、查询结果与工具回执。";
        }
    }
}
